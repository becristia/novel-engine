import { test, expect } from '@playwright/test';

test('rebuilds, confirms and corrects sourced memory, previews actual context and invalidates on constraints', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await page.getByRole('button', { name: '新建作品', exact: true }).click();
  await page.getByLabel('作品名称').fill('记忆验收'); await page.getByLabel('作品文件夹').fill('memory-flow');
  await page.getByRole('button', { name: '创建作品', exact: true }).click(); await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByLabel('选择稿件').setInputFiles({ name: '记忆样例.md', mimeType: 'text/markdown', buffer: Buffer.from('## 雨夜归港\n\n林舟把铜钥匙收进衣袋，转身离开了仓库。\n\n## 封存的信\n\n沈砚看着林舟手里的铜钥匙，没有说话。') });
  await page.getByRole('button', { name: '确认导入 2 章' }).click(); await expect(page.getByRole('button', { name: '记忆验收 2 章正式稿' })).toBeVisible();
  await page.getByRole('link', { name: '规划', exact: true }).click(); await page.getByLabel('创作要求', { exact: true }).fill('继续寻找林舟与铜钥匙的线索。');
  await page.getByLabel('本批章节数').fill('1'); await page.getByRole('button', { name: '生成计划', exact: true }).click();
  await page.getByRole('button', { name: '批准本批 1 章' }).click();
  await page.getByRole('link', { name: '故事记忆', exact: true }).click();
  await page.locator('.memory-inspector').getByRole('button', { name: '重建章节记忆' }).click();
  await expect(page.locator('.memory-table tbody tr')).toHaveCount(2);
  await expect(page.getByText('当前条目未采用：尚未确认')).toBeVisible();
  if (await page.getByRole('button', { name: '关闭提示' }).count()) await page.getByRole('button', { name: '关闭提示' }).click();
  await page.screenshot({ path: '.tmp/ui-implementation/memory.png', fullPage: true });
  await page.getByRole('button', { name: '定位原文', exact: true }).click(); await expect(page.getByRole('dialog')).toContainText('铜钥匙'); await page.getByRole('button', { name: '关闭对话框' }).click();
  await page.getByRole('button', { name: '确认这条信息', exact: true }).click();
  await expect(page.getByText('当前条目已采用', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '管理别名', exact: true }).click();
  await page.getByLabel('人物标识').fill('林舟'); await page.getByLabel('别名', { exact: true }).fill('小林，阿舟');
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '纠正信息', exact: true }).click();
  await page.getByLabel('信息内容').fill('一把铜钥匙'); await page.getByRole('button', { name: '保存纠正', exact: true }).click();
  await expect(page.locator('.memory-inspector')).toContainText('林舟持有一把铜钥匙');
  await expect(page.getByRole('button', { name: '作者纠正 · 查看原条目' })).toBeVisible();
  await page.getByRole('button', { name: '作者约束', exact: true }).click();
  await page.getByLabel('独立约束').fill('保留林舟的有限视角。'); await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('button', { name: '重建失效来源' })).toBeEnabled();
  await expect(page.getByRole('button', { name: '纠正信息', exact: true })).toBeDisabled();
  await expect(page.getByText('当前条目未采用：信息已失效或被替代')).toBeVisible();
  await page.getByRole('button', { name: '重建失效来源' }).click();
  await expect(page.getByRole('button', { name: '重建失效来源' })).not.toBeVisible();
  await page.getByRole('tab', { name: '章节摘要', exact: true }).click();
  await expect(page.locator('.memory-table tbody tr')).not.toHaveCount(0);
  expect(errors).toEqual([]);
});
